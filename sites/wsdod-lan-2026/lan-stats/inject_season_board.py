def main() -> int:
    board = json.load(open(BOARD, encoding="utf-8"))
    page = open(PAGE, encoding="utf-8").read()
    names = page_names(page)
    verify_join(board, page_lan_data(page))
    section = render(board, names)

    if START in page:
        # lambda replacement: the section carries backslashes and "\\g"-like
        # text a plain re.sub replacement string would mangle
        new = re.sub(re.escape(START) + r".*?" + re.escape(END) + r"\n?",
                     lambda m: section, page, flags=re.S)
    else:
        if ANCHOR not in page:
            print(f"anchor not found in {PAGE}: {ANCHOR}")
            return 2
        new = page.replace(ANCHOR, section + "\n  " + ANCHOR, 1)

    if "--check" in sys.argv:
        if new != page:
            print("prototype.html stats board is STALE — re-run inject_season_board.py")
            return 1
        print("prototype.html stats board is current")
        return 0

    if new == page:
        print("no change")
        return 0
    with open(PAGE, "w", encoding="utf-8", newline="\n") as f:
        f.write(new)
    n = len(board["views"]["weekend"]["players"])
    print(f"injected unified stats board ({n} players, 3 views) into {PAGE}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
