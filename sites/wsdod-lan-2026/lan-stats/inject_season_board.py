#!/usr/bin/env python3
"""Render season-board.json into design/prototype.html as the LAN leaderboard.

The section is a data block + a renderer, not a static table, because it now
carries the day boards' interaction model — sortable headers, position/team/
style filter chips, medals that follow the current sort and filter. Same
classes, same behaviour, so the two boards read as one system. Like the day
boards, it renders nothing if scripting fails. Idempotent — the section lives
between two markers and is replaced wholesale on each run.

Display names come from the page's own #player-names block (settled in
build_ballots.py), so this board, the day boards and the awards all answer to
one naming rule. The full in-game name stays on each cell's title.

The renderer <script> is extracted into assets/site.js by build_site.py and so
ships to every edition page — it exits early where the board's elements are
absent. The #lanboard-data block only reaches the 2026 page because build_site
routes data blocks by its OWNED table; adding a new block id here means adding
it there too.

    python inject_season_board.py           # rewrite the section
    python inject_season_board.py --check   # exit 1 if the page is stale
"""
