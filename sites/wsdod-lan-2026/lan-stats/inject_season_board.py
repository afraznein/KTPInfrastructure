def page_names(page: str) -> dict:
    """The settled display names, read from the page's #player-names block.

    build_ballots.py derives them (team-prefix strip + flair trim + one-off
    untag) and embeds the answer; reading it back here keeps this board on the
    same rule without a second implementation.
    """
    m = re.search(r'<script id="player-names" type="application/json">(.*?)</script>',
                  page, re.S)
    return json.loads(m.group(1)) if m else {}


def page_lan_data(page: str) -> dict:
    m = re.search(r'<script id="lan-data" type="application/json">(.*?)</script>',
                  page, re.S)
    if not m:
        sys.exit(f"#lan-data block not found in {PAGE}")
    return json.loads(m.group(1))


def verify_join(board: dict, lan_data: dict) -> None:
    """The renderer joins ratings to #lan-data BY NAME. Prove at injection time
    that the join is total, so a silent miss can never put a legacy number (or
    no number) on the page."""
    day_names = {}
    for i, key in enumerate(DAY_KEYS):
        day_names[key] = {p["n"] for p in lan_data["days"][i]["players"]}
        rated = {r["name"] for r in board["views"][key]["players"]}
        if rated != day_names[key]:
            sys.exit(f"{key}: rating/#lan-data name mismatch: "
                     f"only-rated={sorted(rated - day_names[key])!r} "
                     f"only-page={sorted(day_names[key] - rated)!r}")
        for mp, rows in lan_data["days"][i]["maps"].items():
            page_names_ = {p["n"] for p in rows}
            rated_names = set(board["map_ktpr"][key].get(mp, {}))
            if rated_names != page_names_:
                sys.exit(f"{key} {mp}: map rating/#lan-data mismatch: "
                         f"only-rated={sorted(rated_names - page_names_)!r} "
                         f"only-page={sorted(page_names_ - rated_names)!r}")
    for r in board["views"]["weekend"]["players"]:
        for key in DAY_KEYS:
            n = r["names_by_day"].get(key)
            if n is not None and n not in day_names[key]:
                sys.exit(f"weekend: {r['name']!r} claims {key} name {n!r} "
                         f"not present in #lan-data")


def payload(board: dict, names: dict) -> str:
    views = {}
    for key in DAY_KEYS:
        v = board["views"][key]
        players = {}
        for r in v["players"]:
            tier, arch = r["style"].split(" ", 1)
            players[r["name"]] = [r["ktpr"], tier, arch]
        views[key] = {"label": v["label"], "baseline": v["baseline"],
                      "players": players}
    v = board["views"]["weekend"]
    wk = []
    for r in v["players"]:
        tier, arch = r["style"].split(" ", 1)
        wk.append({"n": r["name"], "dn": names.get(r["name"], r["name"]),
                   "tm": r["team"],
                   "d1": r["names_by_day"].get(DAY_KEYS[0]),
                   "d2": r["names_by_day"].get(DAY_KEYS[1]),
                   "ktpr": r["ktpr"], "tier": tier, "arch": arch})
    views["weekend"] = {"label": v["label"], "baseline": v["baseline"],
                        "players": wk}
    data = {"teams": TEAMS, "views": views, "mapKtpr": board["map_ktpr"]}
    # "</" would end the script block early if a name ever carries it
    return json.dumps(data, ensure_ascii=False,
                      separators=(",", ":")).replace("</", "<\\/")


