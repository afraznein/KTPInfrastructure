import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
BOARD = os.path.join(HERE, "season-board.json")
PAGE = os.path.normpath(os.path.join(HERE, "..", "design", "prototype.html"))

START = "<!-- season-board:start (generated by lan-stats/inject_season_board.py) -->"
END = "<!-- season-board:end -->"
ANCHOR = '<section id="awards" data-ed="philly-2026">'

